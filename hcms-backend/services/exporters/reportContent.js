/** Converts a raw faculty stats row into display-ready values shared by every format. */
const toFacultyDisplayRow = (f) => ({
  ...f,
  role: String(f.role || '').replace(/_/g, ' '),
  hasApproved201: yesNo(f.hasApproved201),
  hasApprovedContract: yesNo(f.hasApprovedContract),
  hasApprovedEvaluation: yesNo(f.hasApprovedEvaluation),
  avgEvaluationRating: f.avgEvaluationRating ?? '',
});

