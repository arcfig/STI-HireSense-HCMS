const { COMPLIANCE_STATUSES, COMPLIANCE_DEFINITIONS } = require('../facultyStatsService');

// --------------------------------------------------------
// SHARED REPORT CONTENT
// Single source of truth for every export format (XLSX, PDF, CSV).
// Change a label or column here and all three formats stay consistent.
// --------------------------------------------------------

const REPORT_TITLE = 'Faculty Compliance Statistics';
const REPORT_SCOPE = 'Active (non-archived) faculty accounts';

const yesNo = (value) => (value ? 'Yes' : 'No');

/** Returns `value / total` as a ratio (0-1), or null when a percentage is not meaningful. */
const ratio = (value, total) => (total > 0 ? value / total : 0);

const formatGeneratedAt = (stats) =>
  stats.generatedAt.toLocaleString('en-PH', { timeZone: stats.timezone, dateStyle: 'long', timeStyle: 'short' });

/** Metadata lines printed at the top of every report. */
const buildReportMeta = (stats, generatedBy) => [
  ['Generated', formatGeneratedAt(stats)],
  ['Generated by', generatedBy],
  ['Scope', REPORT_SCOPE],
];

/**
 * Summary sections. Each section is a list of [label, count] rows.
 * `percentOf` (optional) is the denominator for a "% of Total" column.
 */
const buildSummarySections = (stats) => {
  const { summary, documentTotals, expiringSoonDays } = stats;

  return [
    {
      title: 'Faculty Overview',
      percentOf: summary.totalFaculty,
      rows: [
        ['Total faculty members', summary.totalFaculty],
        ['Faculty with at least one HR-approved document', summary.withApprovedDocuments],
        ['Faculty with documents pending HR review', summary.withPendingDocuments],
        ['Faculty with no approved documents (unverified)', summary.withNoApprovedDocuments],
        ['Faculty with rejected documents', summary.withRejectedDocuments],
        ['Faculty with AI-verified certificates', summary.withAiVerifiedCertificates],
        ['Faculty with AI-flagged documents', summary.withAiFlaggedDocuments],
        ['Faculty with expired documents', summary.withExpiredDocuments],
        [`Faculty with documents expiring in ${expiringSoonDays} days`, summary.withExpiringSoonDocuments],
      ],
    },
    {
      title: 'Required Document Coverage',
      percentOf: summary.totalFaculty,
      rows: [
        ['Has approved 201 File / Identification', summary.withApproved201],
        ['Has approved Contract', summary.withApprovedContract],
        ['Has approved Faculty Evaluation', summary.withApprovedEvaluation],
      ],
    },
    {
      title: 'Compliance Status Breakdown',
      percentOf: summary.totalFaculty,
      rows: COMPLIANCE_STATUSES.map((status) => [status, summary.statusCounts[status]]),
    },
    {
      title: 'Document Totals (Active Faculty)',
      percentOf: documentTotals.totalDocuments,
      rows: [
        ['Total documents', documentTotals.totalDocuments],
        ['HR approved', documentTotals.approved],
        ['HR pending', documentTotals.pending],
        ['HR rejected', documentTotals.rejected],
        ['AI verified', documentTotals.aiVerified],
        ['AI flagged (needs review)', documentTotals.aiFlagged],
        ['AI verification failed', documentTotals.aiFailed],
        ['AI verification in progress', documentTotals.aiVerifying],
        ['Expired', documentTotals.expired],
        [`Expiring within ${expiringSoonDays} days`, documentTotals.expiringSoon],
      ],
    },
    {
      title: 'Data Quality',
      rows: [
        ['Archived faculty accounts (excluded)', summary.archivedFacultyExcluded],
        ['Documents not linked to an active faculty account', stats.unlinkedDocuments.documents],
        ['Distinct unlinked names', stats.unlinkedDocuments.distinctNames],
      ],
    },
  ];
};

