const ExcelJS = require('exceljs');
const {
  getFacultyStatistics,
  COMPLIANCE_STATUSES,
  COMPLIANCE_DEFINITIONS,
} = require('../services/facultyStatsService');

const XLSX_MIME = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

// --------------------------------------------------------
// STYLING HELPERS
// --------------------------------------------------------
const BRAND_GREEN = 'FF1B5E20';
const HEADER_FONT = { bold: true, color: { argb: 'FFFFFFFF' } };
const HEADER_FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_GREEN } };
const SECTION_FONT = { bold: true, size: 12, color: { argb: BRAND_GREEN } };
const STATUS_FILLS = {
  'Compliant': 'FFC8E6C9',
  'Pending Review': 'FFFFF9C4',
  'Action Required': 'FFFFCDD2',
  'No Submissions': 'FFE0E0E0',
};

const styleHeaderRow = (row) => {
  row.font = HEADER_FONT;
  row.fill = HEADER_FILL;
  row.alignment = { vertical: 'middle', wrapText: true };
  row.height = 30;
};

/** Builds a table-style sheet with a frozen, filterable header row. */
const addTableSheet = (workbook, name, columns, rows) => {
  const sheet = workbook.addWorksheet(name, { views: [{ state: 'frozen', ySplit: 1 }] });
  sheet.columns = columns;
  sheet.addRows(rows);
  styleHeaderRow(sheet.getRow(1));
  sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };
  return sheet;
};

const yesNo = (value) => (value ? 'Yes' : 'No');

// --------------------------------------------------------
// WORKBOOK BUILDER
// --------------------------------------------------------
const buildWorkbook = (stats, generatedBy) => {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'HireSense HCMS';
  workbook.created = stats.generatedAt;

  const { summary, documentTotals } = stats;

  // ---- Sheet 1: Summary ----
  const sheet = workbook.addWorksheet('Summary');
  sheet.columns = [{ width: 52 }, { width: 18 }, { width: 14 }];

  sheet.addRow(['Faculty Compliance Statistics']).font = { bold: true, size: 16, color: { argb: BRAND_GREEN } };
  sheet.addRow(['Generated', stats.generatedAt.toLocaleString('en-PH', { timeZone: stats.timezone })]);
  sheet.addRow(['Generated by', generatedBy]);
  sheet.addRow(['Scope', 'Active (non-archived) faculty accounts']);
  sheet.addRow([]);

  const addSection = (title, rows, { percentOf } = {}) => {
    sheet.addRow([title]).font = SECTION_FONT;
    const header = sheet.addRow(['Metric', 'Count', percentOf ? '% of Total' : '']);
    styleHeaderRow(header);
    header.height = 20;
    for (const [label, value] of rows) {
      const row = sheet.addRow([label, value, percentOf ? (percentOf > 0 ? value / percentOf : 0) : null]);
      if (percentOf) row.getCell(3).numFmt = '0.0%';
    }
    sheet.addRow([]);
  };

  addSection('Faculty Overview', [
    ['Total faculty members', summary.totalFaculty],
    ['Faculty with at least one HR-approved document', summary.withApprovedDocuments],
    ['Faculty with documents pending HR review', summary.withPendingDocuments],
    ['Faculty with no approved documents (unverified)', summary.withNoApprovedDocuments],
    ['Faculty with rejected documents', summary.withRejectedDocuments],
    ['Faculty with AI-verified certificates', summary.withAiVerifiedCertificates],
    ['Faculty with AI-flagged documents', summary.withAiFlaggedDocuments],
    ['Faculty with expired documents', summary.withExpiredDocuments],
    [`Faculty with documents expiring in ${stats.expiringSoonDays} days`, summary.withExpiringSoonDocuments],
  ], { percentOf: summary.totalFaculty });

  addSection('Required Document Coverage', [
    ['Has approved 201 File / Identification', summary.withApproved201],
    ['Has approved Contract', summary.withApprovedContract],
    ['Has approved Faculty Evaluation', summary.withApprovedEvaluation],
  ], { percentOf: summary.totalFaculty });

  addSection('Compliance Status Breakdown', COMPLIANCE_STATUSES.map((s) => [s, summary.statusCounts[s]]), {
    percentOf: summary.totalFaculty,
  });

  addSection('Document Totals (Active Faculty)', [
    ['Total documents', documentTotals.totalDocuments],
    ['HR approved', documentTotals.approved],
    ['HR pending', documentTotals.pending],
    ['HR rejected', documentTotals.rejected],
    ['AI verified', documentTotals.aiVerified],
    ['AI flagged (needs review)', documentTotals.aiFlagged],
    ['AI verification failed', documentTotals.aiFailed],
    ['AI verification in progress', documentTotals.aiVerifying],
    ['Expired', documentTotals.expired],
    [`Expiring within ${stats.expiringSoonDays} days`, documentTotals.expiringSoon],
  ], { percentOf: documentTotals.totalDocuments });

  addSection('Data Quality', [
    ['Archived faculty accounts (excluded)', summary.archivedFacultyExcluded],
    ['Documents not linked to an active faculty account', stats.unlinkedDocuments.documents],
    ['Distinct unlinked names', stats.unlinkedDocuments.distinctNames],
  ]);

  sheet.addRow(['Definitions']).font = SECTION_FONT;
  for (const [term, definition] of COMPLIANCE_DEFINITIONS) {
    const row = sheet.addRow([term, definition]);
    row.getCell(1).font = { bold: true };
    sheet.mergeCells(row.number, 2, row.number, 3);
    row.getCell(2).alignment = { wrapText: true, vertical: 'top' };
  }

  // ---- Sheet 2: By Department ----
  const deptSheet = addTableSheet(workbook, 'By Department', [
    { header: 'Department', key: 'department', width: 28 },
    { header: 'Faculty', key: 'facultyCount', width: 10 },
    { header: 'Compliant', key: 'Compliant', width: 12 },
    { header: 'Pending Review', key: 'Pending Review', width: 14 },
    { header: 'Action Required', key: 'Action Required', width: 15 },
    { header: 'No Submissions', key: 'No Submissions', width: 15 },
    { header: 'Compliance Rate', key: 'complianceRate', width: 15 },
    { header: 'Total Docs', key: 'totalDocuments', width: 12 },
    { header: 'Approved', key: 'approved', width: 11 },
    { header: 'Pending', key: 'pending', width: 10 },
    { header: 'Rejected', key: 'rejected', width: 10 },
    { header: 'AI Verified', key: 'aiVerified', width: 12 },
    { header: 'AI Flagged', key: 'aiFlagged', width: 12 },
    { header: 'Expired', key: 'expired', width: 10 },
  ], stats.byDepartment);
  deptSheet.getColumn('complianceRate').numFmt = '0.0%';

  // ---- Sheet 3: Faculty Detail ----
  const facultySheet = addTableSheet(workbook, 'Faculty Detail', [
    { header: 'Name', key: 'name', width: 28 },
    { header: 'Username', key: 'username', width: 22 },
    { header: 'Role', key: 'role', width: 14 },
    { header: 'Department', key: 'department', width: 24 },
    { header: 'Compliance Status', key: 'complianceStatus', width: 18 },
    { header: 'Total Docs', key: 'totalDocuments', width: 11 },
    { header: 'Approved', key: 'approved', width: 10 },
    { header: 'Pending', key: 'pending', width: 10 },
    { header: 'Rejected', key: 'rejected', width: 10 },
    { header: 'AI Verified', key: 'aiVerified', width: 11 },
    { header: 'AI Flagged', key: 'aiFlagged', width: 11 },
    { header: 'AI Failed', key: 'aiFailed', width: 10 },
    { header: 'Expired', key: 'expired', width: 10 },
    { header: 'Expiring Soon', key: 'expiringSoon', width: 13 },
    { header: '201/ID Approved', key: 'hasApproved201', width: 15 },
    { header: 'Contract Approved', key: 'hasApprovedContract', width: 17 },
    { header: 'Evaluation Approved', key: 'hasApprovedEvaluation', width: 18 },
    { header: 'Avg Eval Rating', key: 'avgEvaluationRating', width: 15 },
    { header: 'Last Submission', key: 'lastSubmission', width: 15 },
  ], stats.faculty.map((f) => ({
    ...f,
    role: f.role.replace('_', ' '),
    hasApproved201: yesNo(f.hasApproved201),
    hasApprovedContract: yesNo(f.hasApprovedContract),
    hasApprovedEvaluation: yesNo(f.hasApprovedEvaluation),
    avgEvaluationRating: f.avgEvaluationRating ?? '',
  })));
  facultySheet.getColumn('avgEvaluationRating').numFmt = '0.00';
  facultySheet.getColumn('complianceStatus').eachCell({ includeEmpty: false }, (cell, rowNumber) => {
    const argb = STATUS_FILLS[cell.value];
    if (rowNumber > 1 && argb) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb } };
  });

  // ---- Sheet 4: By Document Type ----
  addTableSheet(workbook, 'By Document Type', [
    { header: 'Document Type', key: 'documentType', width: 24 },
    { header: 'Total', key: 'totalDocuments', width: 10 },
    { header: 'Approved', key: 'approved', width: 11 },
    { header: 'Pending', key: 'pending', width: 10 },
    { header: 'Rejected', key: 'rejected', width: 10 },
    { header: 'AI Verified', key: 'aiVerified', width: 12 },
    { header: 'AI Flagged', key: 'aiFlagged', width: 12 },
    { header: 'AI Failed', key: 'aiFailed', width: 11 },
    { header: 'Expired', key: 'expired', width: 10 },
    { header: 'Expiring Soon', key: 'expiringSoon', width: 14 },
  ], stats.byDocumentType);

  return workbook;
};

// --------------------------------------------------------
// CONTROLLER: GET /api/statistics/export-faculty
// --------------------------------------------------------
const exportFacultyStatistics = async (req, res) => {
  try {
    const stats = await getFacultyStatistics();
    const workbook = buildWorkbook(stats, req.user?.username || 'Unknown');

    // Generate the full buffer *before* sending headers so any failure still
    // returns a clean JSON error instead of a truncated/corrupt file.
    const buffer = await workbook.xlsx.writeBuffer();
    const filename = `faculty-statistics-${stats.reportDate}.xlsx`;

    res.setHeader('Content-Type', XLSX_MIME);
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
    res.setHeader('Content-Length', buffer.length);
    // The report contains personnel data; never let browsers or proxies cache it.
    res.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate, private');
    res.setHeader('Pragma', 'no-cache');

    console.log(`[Export] Faculty statistics exported by ${req.user?.username} (${stats.summary.totalFaculty} faculty)`);
    return res.status(200).send(Buffer.from(buffer));
  } catch (error) {
    console.error('Faculty Statistics Export Error:', error);
    return res.status(500).json({ error: 'Failed to generate the faculty statistics export.' });
  }
};

module.exports = { exportFacultyStatistics };
